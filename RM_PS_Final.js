
// 01. Solve Me First
// Write a function that returns the sum of two integers.

/**
  * @param {number} a
  * @param {number} b
  * @return {number}
  */
var solveMeFirst = function(a, b) {
  return a + b;
};


// 02. Multiply
// Write a function that returns the product of two numbers.

/**
  * @param {number} a
  * @param {number} b
  * @return {number}
  */
var multiply = function(a, b) {
  return a * b;
};